CREATE TABLE IF NOT EXISTS app_products (name TEXT PRIMARY KEY, base_price REAL NOT NULL DEFAULT 0, price REAL NOT NULL DEFAULT 0, page_url TEXT NOT NULL DEFAULT '', requires_mac INTEGER NOT NULL DEFAULT 1, icon_png TEXT, icon_shape TEXT NOT NULL DEFAULT 'rounded' CHECK (icon_shape IN ('square','rounded','circle')), icon_fit TEXT NOT NULL DEFAULT 'contain' CHECK (icon_fit IN ('contain','cover')), icon_bg TEXT NOT NULL DEFAULT '#ffffff', updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS store_settings (id INTEGER PRIMARY KEY CHECK (id=1), logo_png TEXT, logo_width INTEGER NOT NULL DEFAULT 44 CHECK (logo_width BETWEEN 32 AND 160), logo_height INTEGER NOT NULL DEFAULT 44 CHECK (logo_height BETWEEN 32 AND 160), logo_fit TEXT NOT NULL DEFAULT 'contain' CHECK (logo_fit IN ('contain','cover')), logo_url TEXT NOT NULL DEFAULT '', updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
